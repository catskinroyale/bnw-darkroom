//! The About window: version, this project's licences (with full texts), the data
//! sources and every third-party component compiled into the app with its licence.

use eframe::egui;
use serde::Deserialize;

use crate::version;

const APACHE_TEXT: &str = include_str!("../../../LICENSE-APACHE");
const MIT_TEXT: &str = include_str!("../../../LICENSE-MIT");
const LIGHTCRAFT_TEXT: &str = include_str!("../assets/LICENSE-LightCraft-MIT");
const INTER_TEXT: &str = include_str!("../assets/fonts/OFL-Inter.txt");
const THIRD_PARTY_JSON: &str = include_str!("../assets/third-party-licenses.json");
const ICON_PNG: &[u8] = include_bytes!("../../../packaging/macos/icon_1024.png");

#[derive(Deserialize)]
struct ThirdParty {
    crates: Vec<Component>,
}

#[derive(Deserialize)]
pub struct Component {
    pub name: String,
    pub version: String,
    pub license: String,
    pub repository: String,
}

/// Third-party crates compiled into the app (generated by `tools/gen_licenses.py`).
pub fn components() -> Vec<Component> {
    serde_json::from_str::<ThirdParty>(THIRD_PARTY_JSON)
        .map(|t| t.crates)
        .unwrap_or_default()
}

pub struct About {
    pub open: bool,
    /// Set when the user presses "Check for Updates…"; the app takes it.
    pub check_requested: bool,
    filter: String,
    components: Vec<Component>,
    icon: Option<egui::TextureHandle>,
}

impl Default for About {
    fn default() -> Self {
        Self {
            open: false,
            check_requested: false,
            filter: String::new(),
            components: components(),
            icon: None,
        }
    }
}

/// (licence, number of components using it), most common first.
fn licence_summary(components: &[Component]) -> Vec<(String, usize)> {
    let mut counts: std::collections::BTreeMap<String, usize> = Default::default();
    for c in components {
        *counts.entry(c.license.clone()).or_default() += 1;
    }
    let mut v: Vec<_> = counts.into_iter().collect();
    v.sort_by(|a, b| b.1.cmp(&a.1).then_with(|| a.0.cmp(&b.0)));
    v
}

fn licence_text(ui: &mut egui::Ui, id: &str, title: &str, text: &str) {
    egui::CollapsingHeader::new(title)
        .id_salt(id)
        .show(ui, |ui| {
            egui::ScrollArea::vertical()
                .id_salt(id)
                .max_height(180.0)
                .show(ui, |ui| {
                    ui.label(egui::RichText::new(text).monospace().small());
                });
        });
}

impl About {
    fn icon(&mut self, ctx: &egui::Context) -> Option<egui::TextureHandle> {
        if self.icon.is_none()
            && let Ok(img) = image::load_from_memory(ICON_PNG)
        {
            let small = img.thumbnail(192, 192).to_rgba8();
            let size = [small.width() as usize, small.height() as usize];
            let colour = egui::ColorImage::from_rgba_unmultiplied(size, small.as_raw());
            self.icon = Some(ctx.load_texture("about-icon", colour, egui::TextureOptions::LINEAR));
        }
        self.icon.clone()
    }

    pub fn show(&mut self, ctx: &egui::Context) {
        if !self.open {
            return;
        }
        let icon = self.icon(ctx);
        let mut open = self.open;
        egui::Window::new("About BW Darkroom")
            .open(&mut open)
            .collapsible(false)
            .resizable(false)
            .anchor(egui::Align2::CENTER_CENTER, [0.0, 0.0])
            .show(ctx, |ui| {
                ui.set_width(520.0);
                ui.horizontal(|ui| {
                    if let Some(icon) = &icon {
                        ui.add(egui::Image::new(icon).fit_to_exact_size(egui::vec2(72.0, 72.0)));
                    }
                    ui.vertical(|ui| {
                        ui.heading("BW Darkroom");
                        ui.label(format!("Version {}", version::full()))
                            .on_hover_text("Semantic version (MAJOR.MINOR.PATCH) and the git commit of this build.");
                        ui.label(egui::RichText::new("Black-and-white film, developer and darkroom emulation.").weak());
                        if ui
                            .small_button("Check for Updates…")
                            .on_hover_text("Ask GitHub whether a newer version has been released")
                            .clicked()
                        {
                            self.check_requested = true;
                        }
                    });
                });
                ui.label(
                    egui::RichText::new(
                        "Film and developer parameters are illustrative, not calibrated emulations of the named products.",
                    )
                    .small()
                    .weak(),
                );

                ui.separator();
                ui.label(egui::RichText::new("Licences").strong());
                egui::Grid::new("own-licences").num_columns(2).spacing([12.0, 4.0]).show(ui, |ui| {
                    ui.label("BW Darkroom app, CLI and engine crates");
                    ui.label("Apache-2.0");
                    ui.end_row();
                    ui.label("bw-core engine foundation");
                    ui.label("MIT");
                    ui.end_row();
                });
                licence_text(ui, "apache", "Apache License 2.0 — full text", APACHE_TEXT);
                licence_text(ui, "mit", "MIT License — full text", MIT_TEXT);
                licence_text(ui, "lightcraft", "LightCraft (interface design) — MIT License", LIGHTCRAFT_TEXT);
                licence_text(ui, "inter", "Inter typeface — SIL Open Font License 1.1", INTER_TEXT);

                ui.separator();
                ui.label(egui::RichText::new("Data and components").strong());
                for (what, source) in [
                    ("Raw decoding", "LightCraft lightcraft-raw — MIT OR Apache-2.0"),
                    ("Camera colour matrices", "rawtoaces-data, Academy Software Foundation — Apache-2.0"),
                    ("Development times", "Massive Dev Chart, Digital Truth — not covered by this project's licences"),
                    ("Interface design", "Adapted from LightCraft, ArtCraft Team and LightCraft contributors — MIT"),
                    ("Interface font", "Inter, Rasmus Andersson — SIL OFL 1.1"),
                    ("Fallback fonts", "egui default fonts — Ubuntu Font Licence, SIL OFL 1.1"),
                ] {
                    ui.horizontal_wrapped(|ui| {
                        ui.label(egui::RichText::new(format!("{what}:")).weak());
                        ui.label(source);
                    });
                }

                ui.separator();
                ui.horizontal(|ui| {
                    ui.label(egui::RichText::new(format!("Third-party components ({})", self.components.len())).strong());
                    ui.with_layout(egui::Layout::right_to_left(egui::Align::Center), |ui| {
                        ui.add(egui::TextEdit::singleline(&mut self.filter).hint_text("Filter").desired_width(140.0))
                            .on_hover_text("Filter by crate name or licence");
                    });
                });
                let summary = licence_summary(&self.components)
                    .into_iter()
                    .take(4)
                    .map(|(l, n)| format!("{l} ({n})"))
                    .collect::<Vec<_>>()
                    .join(" · ");
                ui.label(egui::RichText::new(summary).small().weak());
                let needle = self.filter.to_lowercase();
                egui::ScrollArea::vertical().id_salt("components").max_height(220.0).show(ui, |ui| {
                    egui::Grid::new("components").num_columns(3).striped(true).spacing([12.0, 2.0]).show(ui, |ui| {
                        for c in self.components.iter().filter(|c| {
                            needle.is_empty()
                                || c.name.to_lowercase().contains(&needle)
                                || c.license.to_lowercase().contains(&needle)
                        }) {
                            let name = ui.label(&c.name);
                            if !c.repository.is_empty() {
                                name.on_hover_text(&c.repository);
                            }
                            ui.label(egui::RichText::new(&c.version).weak());
                            ui.label(&c.license);
                            ui.end_row();
                        }
                    });
                });
            });
        self.open = open;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn third_party_list_is_present_and_complete() {
        let list = components();
        assert!(list.len() > 50, "only {} components listed", list.len());
        for name in [
            "eframe",
            "image",
            "lightcraft-raw",
            "kamadak-exif",
            "rayon",
            "serde",
        ] {
            assert!(
                list.iter().any(|c| c.name == name),
                "{name} missing: re-run tools/gen_licenses.py"
            );
        }
        assert!(list.iter().all(|c| !c.license.is_empty()));
        assert!(
            !list.iter().any(|c| c.name.starts_with("bw-")),
            "workspace crates are first-party"
        );
    }

    #[test]
    fn licence_texts_are_bundled() {
        assert!(APACHE_TEXT.contains("Apache License") && APACHE_TEXT.contains("Version 2.0"));
        assert!(MIT_TEXT.starts_with("MIT License"));
        assert!(LIGHTCRAFT_TEXT.contains("LightCraft contributors"));
        assert!(INTER_TEXT.contains("SIL OPEN FONT LICENSE"));
    }
}
